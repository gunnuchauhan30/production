-- ============================================================
-- CHANDA ENTERPRISES — PPE (Production Planning & Execution) MODULE
-- Database Schema v2.0 (PostgreSQL) — STANDALONE
--
-- ARCHITECTURE CHANGE FROM v1.1 (confirmed decision):
--   PPE is now a FULLY SEPARATE system — its own database, its own
--   backend, its own login. It does NOT connect to the live Store
--   database in any way (no shared DB, no read-only user, no API
--   call into Store). Store is completely untouched.
--
--   The link between the two systems is a PERSON, not a program:
--   Store prints a Route Card (job_card_no, part, issued qty).
--   A PPE user reads that printed card and types the same values
--   into the new "route_cards" table below (route-card-print.html
--   already contains this data, it is just re-keyed by a person
--   instead of pulled automatically).
--
--   Because route_cards now lives INSIDE this same database, every
--   other PPE table can use a real, enforced foreign key against it
--   -- the FK problem from v1.0/v1.1 (job_card_no not unique in a
--   different system's table) no longer exists.
--
-- Run with:  psql -U your_user -d chanda_ppe -f ppe_module_schema_v2.0.sql
-- (on a NEW, separate database — does not touch chanda_store)
-- ============================================================

-- ------------------------------------------------------------
-- 0. STANDALONE LOGIN
-- PPE has its own users table -- it is a separate database, so it
-- cannot foreign-key into Store's users table. A person with access
-- to both systems will simply have an account in each.
-- ------------------------------------------------------------
CREATE TYPE ppe_role_enum AS ENUM ('planning', 'operator', 'qa', 'dispatch', 'admin');

CREATE TABLE ppe_users (
    id              SERIAL PRIMARY KEY,
    username        VARCHAR(80) UNIQUE NOT NULL,
    password_hash   VARCHAR(255) NOT NULL,
    full_name       VARCHAR(150),
    role            ppe_role_enum NOT NULL,
    is_active       BOOLEAN DEFAULT TRUE,
    created_at      TIMESTAMP DEFAULT NOW()
);


-- ------------------------------------------------------------
-- 1. ROUTE CARDS — manually entered from the printed Store document
-- This is the NEW anchor table. A PPE user reads the physical /
-- printed Route Card (generated by Store, unchanged) and re-types
-- its header fields here once. Everything downstream in PPE links
-- to this table's id with a normal, enforced foreign key.
-- ------------------------------------------------------------
CREATE TABLE route_cards (
    id              SERIAL PRIMARY KEY,
    job_card_no     VARCHAR(50) UNIQUE NOT NULL,   -- as printed on the Store route card
    part_number     VARCHAR(80) NOT NULL,
    material_name   VARCHAR(120),
    issued_qty      NUMERIC(12,2) NOT NULL CHECK (issued_qty >= 0),
    department      VARCHAR(80),
    customer        VARCHAR(120),
    entered_by      INTEGER REFERENCES ppe_users(id),
    entered_at      TIMESTAMP DEFAULT NOW()
);

CREATE INDEX idx_route_cards_job_card_no ON route_cards(job_card_no);
CREATE INDEX idx_route_cards_part ON route_cards(part_number);


-- ------------------------------------------------------------
-- 2. CUSTOMER SCHEDULE & PRODUCTION PLANNING
-- ------------------------------------------------------------
CREATE TYPE schedule_status_enum AS ENUM ('pending', 'planned', 'issued');

CREATE TABLE customer_schedule (
    id              SERIAL PRIMARY KEY,
    customer        VARCHAR(120) NOT NULL,
    part_number     VARCHAR(80)  NOT NULL,
    qty             NUMERIC(12,2) NOT NULL CHECK (qty > 0),
    required_date   DATE NOT NULL,
    status          schedule_status_enum DEFAULT 'pending',
    created_by      INTEGER REFERENCES ppe_users(id),
    created_at      TIMESTAMP DEFAULT NOW()
);

CREATE INDEX idx_customer_schedule_status ON customer_schedule(status);
CREATE INDEX idx_customer_schedule_date ON customer_schedule(required_date);


-- ------------------------------------------------------------
-- 3. DAILY PRODUCTION / OEE ENTRIES
-- Matches OEE_Calculation_Sheet (HANDLE BAR, July 2026) column-for-column.
-- Independent of route_cards by design (same as v1.1) -- a pure
-- machine/operator/operation daily log.
-- ------------------------------------------------------------
CREATE TABLE production_oee_entries (
    id                          SERIAL PRIMARY KEY,
    sr_no                       INTEGER,
    entry_date                  DATE NOT NULL,
    shift                       VARCHAR(10),
    operator_name               VARCHAR(150),
    machine_no                  VARCHAR(30),
    operation_name              VARCHAR(100),
    part_name                   VARCHAR(100),
    standard_cycle_time_sec     NUMERIC(10,2),
    ok_qty                      NUMERIC(12,2) DEFAULT 0,
    rejected_qty                NUMERIC(12,2) DEFAULT 0,
    rejection_reason            VARCHAR(150),
    total_qty_produced          NUMERIC(12,2) GENERATED ALWAYS AS
                                     (COALESCE(ok_qty,0) + COALESCE(rejected_qty,0)) STORED,
    total_time_min              NUMERIC(10,2),
    run_time_min                NUMERIC(10,2),
    run_time_sec                NUMERIC(10,2) GENERATED ALWAYS AS
                                     (COALESCE(run_time_min,0) * 60) STORED,
    down_time_min                NUMERIC(10,2) DEFAULT 0,
    down_time_reason             VARCHAR(150),
    availability                 NUMERIC(6,5),
    performance                  NUMERIC(6,5),
    quality                      NUMERIC(6,5),
    oee                          NUMERIC(6,5) GENERATED ALWAYS AS
                                     (COALESCE(availability,0) * COALESCE(performance,0) * COALESCE(quality,0)) STORED,
    entry_by                     INTEGER REFERENCES ppe_users(id),
    created_at                   TIMESTAMP DEFAULT NOW()
);

CREATE INDEX idx_oee_date ON production_oee_entries(entry_date);
CREATE INDEX idx_oee_machine ON production_oee_entries(machine_no);
CREATE INDEX idx_oee_operation ON production_oee_entries(operation_name);

-- Availability/performance/quality computed safely by trigger (generated
-- columns are not yet populated inside a BEFORE trigger -- recompute locally).
CREATE OR REPLACE FUNCTION fn_trg_oee_calc() RETURNS TRIGGER AS $$
DECLARE
    v_total_qty NUMERIC(12,2) := COALESCE(NEW.ok_qty,0) + COALESCE(NEW.rejected_qty,0);
    v_run_time_sec NUMERIC(10,2) := COALESCE(NEW.run_time_min,0) * 60;
BEGIN
    NEW.availability := CASE WHEN COALESCE(NEW.total_time_min,0) > 0
        THEN ROUND(NEW.run_time_min / NEW.total_time_min, 5) ELSE NULL END;
    NEW.performance := CASE WHEN v_run_time_sec > 0
        THEN ROUND((NEW.standard_cycle_time_sec * v_total_qty) / v_run_time_sec, 5) ELSE NULL END;
    NEW.quality := CASE WHEN v_total_qty > 0
        THEN ROUND(NEW.ok_qty / v_total_qty, 5) ELSE NULL END;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_oee_calc
    BEFORE INSERT OR UPDATE ON production_oee_entries
    FOR EACH ROW EXECUTE FUNCTION fn_trg_oee_calc();


-- ------------------------------------------------------------
-- 4. PRODUCTION ENTRIES — route-card-linked
-- route_card_id is now a REAL, enforced foreign key -- route_cards
-- lives in this same database, so there is no cross-system FK problem.
-- ------------------------------------------------------------
CREATE TABLE production_entries (
    id              SERIAL PRIMARY KEY,
    route_card_id   INTEGER NOT NULL REFERENCES route_cards(id),
    operation_name  VARCHAR(100) NOT NULL,
    operation_seq   INTEGER NOT NULL,
    entry_date      DATE DEFAULT CURRENT_DATE,
    shift           VARCHAR(10),
    operator_name   VARCHAR(150),
    machine_no      VARCHAR(30),
    qty_planned     NUMERIC(12,2) NOT NULL DEFAULT 0,
    qty_produced    NUMERIC(12,2) NOT NULL DEFAULT 0,
    ok_qty          NUMERIC(12,2) NOT NULL DEFAULT 0,
    rejected_qty    NUMERIC(12,2) NOT NULL DEFAULT 0,
    rework_qty      NUMERIC(12,2) NOT NULL DEFAULT 0,
    hold_qty        NUMERIC(12,2) NOT NULL DEFAULT 0,
    balance_qty     NUMERIC(12,2) GENERATED ALWAYS AS (qty_planned - qty_produced) STORED,
    down_time_min   NUMERIC(10,2) DEFAULT 0,
    down_time_reason VARCHAR(150),
    remarks         TEXT,
    entry_by        INTEGER REFERENCES ppe_users(id),
    created_at      TIMESTAMP DEFAULT NOW()
);

CREATE INDEX idx_prod_entries_route_card ON production_entries(route_card_id);
CREATE INDEX idx_prod_entries_seq ON production_entries(route_card_id, operation_seq);
CREATE INDEX idx_prod_entries_date ON production_entries(entry_date);

-- View: cumulative progress per route card + operation. The app uses
-- this to pre-fill "qty_planned" on the NEXT operation's entry form.
CREATE OR REPLACE VIEW v_operation_progress AS
SELECT
    route_card_id,
    operation_seq,
    operation_name,
    SUM(qty_produced)  AS total_produced,
    SUM(ok_qty)        AS total_ok,
    SUM(rejected_qty)  AS total_rejected,
    SUM(rework_qty)    AS total_rework,
    SUM(hold_qty)      AS total_hold
FROM production_entries
GROUP BY route_card_id, operation_seq, operation_name;

-- View: route card's last (highest-sequence) operation, used to check
-- production-complete status against route_cards.issued_qty and to
-- size the Finished Goods entry.
CREATE OR REPLACE VIEW v_route_card_last_operation AS
SELECT DISTINCT ON (route_card_id)
    route_card_id,
    operation_seq,
    operation_name,
    SUM(qty_produced) OVER (PARTITION BY route_card_id, operation_seq) AS total_produced_last_op
FROM production_entries
ORDER BY route_card_id, operation_seq DESC, entry_date DESC;


-- ------------------------------------------------------------
-- 5. PDI (Pre-Dispatch Inspection) — two stages
-- in_process: operator-level check after an operation
-- final: QA check before Finished Goods
-- ------------------------------------------------------------
CREATE TYPE pdi_stage_enum  AS ENUM ('in_process', 'final');
CREATE TYPE pdi_result_enum AS ENUM ('pass', 'fail');

CREATE TABLE pdi_checks (
    id              SERIAL PRIMARY KEY,
    route_card_id   INTEGER NOT NULL REFERENCES route_cards(id),
    stage           pdi_stage_enum NOT NULL,
    inspector_id    INTEGER REFERENCES ppe_users(id),
    result          pdi_result_enum NOT NULL,
    remarks         TEXT,
    checked_at      TIMESTAMP DEFAULT NOW(),
    UNIQUE (route_card_id, stage)
);

CREATE INDEX idx_pdi_route_card ON pdi_checks(route_card_id);
CREATE INDEX idx_pdi_stage ON pdi_checks(stage);


-- ------------------------------------------------------------
-- 6. FINISHED GOODS
-- Auto-created when a route card's FINAL PDI result = 'pass'.
-- ------------------------------------------------------------
CREATE TABLE finished_goods (
    id              SERIAL PRIMARY KEY,
    route_card_id   INTEGER NOT NULL REFERENCES route_cards(id),
    fg_qty          NUMERIC(12,2) NOT NULL CHECK (fg_qty >= 0),
    fg_date         DATE DEFAULT CURRENT_DATE,
    warehouse       VARCHAR(50),
    created_at      TIMESTAMP DEFAULT NOW()
);

CREATE INDEX idx_fg_route_card ON finished_goods(route_card_id);
CREATE INDEX idx_fg_date ON finished_goods(fg_date);

CREATE OR REPLACE FUNCTION fn_trg_pdi_to_fg() RETURNS TRIGGER AS $$
DECLARE
    v_qty NUMERIC(12,2);
BEGIN
    IF NEW.stage = 'final' AND NEW.result = 'pass' THEN
        SELECT total_produced_last_op INTO v_qty
        FROM v_route_card_last_operation
        WHERE route_card_id = NEW.route_card_id;

        IF FOUND THEN
            INSERT INTO finished_goods (route_card_id, fg_qty)
            VALUES (NEW.route_card_id, COALESCE(v_qty, 0));
        END IF;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_pdi_to_fg
    AFTER INSERT ON pdi_checks
    FOR EACH ROW EXECUTE FUNCTION fn_trg_pdi_to_fg();


-- ------------------------------------------------------------
-- 7. DISPATCH
-- One route card can have more than one dispatch row (partial shipments).
-- ------------------------------------------------------------
CREATE TYPE dispatch_status_enum AS ENUM ('pending', 'on_time', 'delayed');

CREATE TABLE dispatch (
    id                      SERIAL PRIMARY KEY,
    route_card_id           INTEGER NOT NULL REFERENCES route_cards(id),
    order_no                VARCHAR(50),
    schedule_date           DATE,
    actual_dispatch_date    DATE,
    qty_dispatched          NUMERIC(12,2) CHECK (qty_dispatched >= 0),
    delay_days              INTEGER GENERATED ALWAYS AS
                                 (CASE WHEN actual_dispatch_date IS NOT NULL AND schedule_date IS NOT NULL
                                       THEN (actual_dispatch_date - schedule_date)
                                       ELSE NULL END) STORED,
    status                  dispatch_status_enum DEFAULT 'pending',
    created_at              TIMESTAMP DEFAULT NOW()
);

CREATE INDEX idx_dispatch_route_card ON dispatch(route_card_id);
CREATE INDEX idx_dispatch_status ON dispatch(status);

CREATE OR REPLACE FUNCTION fn_trg_dispatch_status() RETURNS TRIGGER AS $$
BEGIN
    IF NEW.actual_dispatch_date IS NULL THEN
        NEW.status := 'pending';
    ELSIF NEW.actual_dispatch_date <= NEW.schedule_date THEN
        NEW.status := 'on_time';
    ELSE
        NEW.status := 'delayed';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_dispatch_status
    BEFORE INSERT OR UPDATE ON dispatch
    FOR EACH ROW EXECUTE FUNCTION fn_trg_dispatch_status();


